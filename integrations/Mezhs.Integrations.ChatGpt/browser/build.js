// The C# browser host extracts exactly one embedded resource as a standalone .js file.
// Resolve local modules at packaging time; no runtime files or relative imports are needed.
const fs = require('node:fs');
const path = require('node:path');

const directory = __dirname;
const sourceDirectory = path.join(directory, 'modules');
const modules = fs.readdirSync(sourceDirectory)
  .filter(name => name.endsWith('.js'))
  .sort();
const factories = modules.map(name => {
  const id = './' + name;
  const source = fs.readFileSync(path.join(sourceDirectory, name), 'utf8');
  return '    ' + JSON.stringify(id) + ': function(module, exports, require) {\n' +
    source + '\n    }';
}).join(',\n');

const output = [
  '// Generated by browser/build.js. Edit browser/modules/*.js instead.',
  '(function() {',
  '  const factories = {',
  factories,
  '  };',
  '  const cache = Object.create(null);',
  '  function bundledRequire(id) {',
  '    if (Object.prototype.hasOwnProperty.call(factories, id)) {',
  '      if (Object.prototype.hasOwnProperty.call(cache, id)) return cache[id].exports;',
  '      const loaded = { exports: {} };',
  '      cache[id] = loaded;',
  '      factories[id](loaded, loaded.exports, bundledRequire);',
  '      return loaded.exports;',
  '    }',
  '    if (id.startsWith(".")) throw new Error("Missing packaged ChatGPT module: " + id);',
  '    return require(id);',
  '  }',
  '  module.exports = bundledRequire("./entry.js");',
  '})();',
  ''
].join('\n');

const destination = path.join(directory, 'chatgpt.ts');
const previous = fs.existsSync(destination) ? fs.readFileSync(destination, 'utf8') : null;
if (process.argv.includes('--check')) {
  if (previous !== output) {
    console.error('ChatGPT browser bundle is stale. Run node browser/build.js');
    process.exitCode = 1;
  } else {
    console.log('ChatGPT browser bundle is current.');
  }
} else if (previous !== output) {
  fs.writeFileSync(destination, output);
  console.log('Generated ChatGPT browser module (' + modules.length + ' sources).');
} else {
  console.log('ChatGPT browser module unchanged.');
}
